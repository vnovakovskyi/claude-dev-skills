#!/usr/bin/env bash

# Rebuild docs/INDEX.md of the dev-skills knowledge base from the frontmatter of
# docs/cases/*/case.md and docs/codebase/*.md.
#
# Usage: reindex.sh [docs-root]     (default: ./docs)
#
# Prints a warning to stderr for every card with a missing or unknown field.
# Exits 0 even with warnings, so a bad card never blocks the index.

set -euo pipefail

ROOT="${1:-docs}"
ROOT="${ROOT%/}"

if [[ ! -d "$ROOT" ]]; then
  echo "reindex: no such directory: $ROOT" >&2
  exit 1
fi

# Print the frontmatter of $1 as "key<TAB>value" lines. Inline lists lose their
# brackets and quotes: [a, "b"] -> a, b
frontmatter() {
  awk '
    NR == 1 { if ($0 != "---") exit; next }
    $0 == "---" { exit }
    {
      i = index($0, ":")
      if (i == 0) next
      key = substr($0, 1, i - 1)
      val = substr($0, i + 1)
      gsub(/^[ \t]+|[ \t]+$/, "", key)
      gsub(/^[ \t]+|[ \t]+$/, "", val)
      if (val ~ /^\[.*\]$/) {
        val = substr(val, 2, length(val) - 2)
        gsub(/"/, "", val)
        gsub(/[ \t]*,[ \t]*/, ", ", val)
      } else if (val ~ /^".*"$/) {
        val = substr(val, 2, length(val) - 2)
      }
      print key "\t" val
    }
  ' "$1"
}

field() {
  printf '%s\n' "$1" | awk -F '\t' -v k="$2" '$1 == k { print $2; exit }'
}

warn() {
  echo "reindex: $1: $2" >&2
}

ACTIVE=""
CLOSED=""
NOTES=""
CASES=0
COUNT_NOTES=0

for card in "$ROOT"/cases/*/case.md; do
  [[ -f "$card" ]] || continue
  slug="$(basename "$(dirname "$card")")"
  fm="$(frontmatter "$card")"
  if [[ -z "$fm" ]]; then
    warn "cases/$slug/case.md" "no frontmatter"
    title="$(awk '/^# / { sub(/^# /, ""); print; exit }' "$card")"
    ACTIVE+="${slug:0:10}"$'\t'"- ${slug:0:10} [?][?] ? — ${title:-$slug} → cases/${slug}/"$'\n'
    CASES=$((CASES + 1))
    continue
  fi

  kind="$(field "$fm" kind)"
  status="$(field "$fm" status)"
  summary="$(field "$fm" summary)"
  updated="$(field "$fm" updated)"
  who="$(field "$fm" services)"
  [[ -z "$who" ]] && who="$(field "$fm" repos)"

  for key in kind status summary updated; do
    [[ -n "$(field "$fm" "$key")" ]] || warn "cases/$slug/case.md" "missing $key"
  done
  case "$kind" in
    incident|error|logs|upgrade|feature|review|infra|question|"") ;;
    *) warn "cases/$slug/case.md" "unknown kind '$kind'" ;;
  esac
  [[ -z "$summary" ]] && summary="$(field "$fm" title)"
  [[ -z "$updated" ]] && updated="$(field "$fm" created)"
  [[ -z "$updated" ]] && updated="${slug:0:10}"

  line="${updated}"$'\t'"- ${updated} [${status:-?}][${kind:-?}] ${who:-?} — ${summary:-?} → cases/${slug}/"
  case "$status" in
    open|in-progress|in-review) ACTIVE+="$line"$'\n' ;;
    solved|wont-fix|abandoned) CLOSED+="$line"$'\n' ;;
    *)
      warn "cases/$slug/case.md" "unknown status '${status}'"
      ACTIVE+="$line"$'\n'
      ;;
  esac
  CASES=$((CASES + 1))
done

for note in "$ROOT"/codebase/*.md; do
  [[ -f "$note" ]] || continue
  name="$(basename "$note")"
  fm="$(frontmatter "$note")"
  if [[ -z "$fm" ]]; then
    warn "codebase/$name" "no frontmatter"
    title="$(awk '/^# / { sub(/^# /, ""); print; exit }' "$note")"
    NOTES+="0000-00-00"$'\t'"- ? ? — ${title:-$name} → codebase/${name}"$'\n'
    COUNT_NOTES=$((COUNT_NOTES + 1))
    continue
  fi
  summary="$(field "$fm" summary)"
  [[ -z "$summary" ]] && summary="$(field "$fm" title)"
  updated="$(field "$fm" updated)"
  repos="$(field "$fm" repos)"
  for key in summary updated repos; do
    [[ -n "$(field "$fm" "$key")" ]] || warn "codebase/$name" "missing $key"
  done
  NOTES+="${updated:-0000-00-00}"$'\t'"- ${updated:-?} ${repos:-?} — ${summary:-$name} → codebase/${name}"$'\n'
  COUNT_NOTES=$((COUNT_NOTES + 1))
done

section() {
  local title="$1" body="$2"
  echo "## $title"
  echo
  if [[ -z "$body" ]]; then
    echo "None."
  else
    printf '%s' "$body" | sort -r | cut -f2-
  fi
  echo
}

TMP="$(mktemp "$ROOT/.INDEX.md.XXXXXX")"
{
  echo "# Knowledge base index"
  echo
  echo "Generated by reindex.sh from the frontmatter of cases/*/case.md and codebase/*.md."
  echo "Do not edit by hand: change the card and run reindex.sh again."
  echo
  echo "Line format: updated [status][kind] services — summary → path"
  echo
  section "Active cases (open, in progress, in review)" "$ACTIVE"
  section "Closed cases (solved, won't fix, abandoned)" "$CLOSED"
  section "Codebase notes" "$NOTES"
} >"$TMP"
mv "$TMP" "$ROOT/INDEX.md"

echo "reindex: $CASES cases, $COUNT_NOTES codebase notes → $ROOT/INDEX.md"
